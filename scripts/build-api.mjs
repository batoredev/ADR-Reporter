// Builds the Supabase Edge Function "api" as one self-contained file
// (npm run build:api): supabase/functions/api/index.ts.
// npm packages are not bundled; they are imported as npm:<package>@<version>
// (the versions installed here), which Supabase's Deno runtime loads itself.
// The file can be deployed with the Supabase CLI or pasted into the dashboard editor.
import { readFileSync } from "node:fs";
import { build } from "esbuild";

const OUT = "supabase/functions/api/index.ts";

const version = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8")).version;

const npmSpecifiers = {
  name: "npm-specifiers",
  setup(b) {
    // "server-only" guards against importing server code into the browser bundle; it has no meaning here.
    b.onResolve({ filter: /^server-only$/ }, () => ({ path: "server-only", namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "", loader: "js" }));
    // Bare package imports; "@/..." paths are our own code (tsconfig paths) and node: built-ins stay as they are.
    b.onResolve({ filter: /^[^./]/ }, ({ path }) => {
      if (path.startsWith("@/") || path.startsWith("node:") || path.startsWith("npm:")) return undefined;
      const parts = path.split("/");
      const name = path.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
      let subpath = path.slice(name.length);
      // Prisma's Node.js runtime reads process.pid when it loads, which Supabase's Edge Runtime does not
      // provide; its edge build has the same interface without that.
      if (path === "@prisma/client/runtime/client") subpath = "/runtime/wasm-compiler-edge";
      return { path: `npm:${name}@${version(name)}${subpath}`, external: true };
    });
  },
};

await build({
  entryPoints: ["src/server/api/edge.ts"],
  outfile: OUT,
  bundle: true,
  minify: true,
  format: "esm",
  platform: "node",
  target: "es2022",
  tsconfig: "tsconfig.json",
  plugins: [npmSpecifiers],
  legalComments: "none",
  banner: {
    js: [
      "// @ts-nocheck",
      '// ADR Reporter API: Supabase Edge Function "api" (turn JWT verification off for this function).',
      "// Generated by `npm run build:api` from src/server. Do not edit; change src/server and rebuild.",
      'import __process from "node:process";',
      'import { Buffer as __Buffer } from "node:buffer";',
      "globalThis.process ??= __process;",
      "globalThis.Buffer ??= __Buffer;",
    ].join("\n"),
  },
});
console.log(`Built ${OUT} (${Math.round(readFileSync(OUT).length / 1024)} KB)`);
